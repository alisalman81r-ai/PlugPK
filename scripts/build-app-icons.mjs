const WEIGHTS = ['regular', 'fill', 'light', 'bold']
const DEFS = path.resolve('node_modules/@phosphor-icons/react/dist/defs')

const kebab = (key) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)

function weightsOf(phosphorName) {
  const file = path.join(DEFS, `${phosphorName}.es.js`)
  if (!fs.existsSync(file)) throw new Error(`Phosphor has no "${phosphorName}"`)
  const src = fs.readFileSync(file, 'utf8')
  const out = {}
  for (const weight of WEIGHTS) {
    const start = src.indexOf(`"${weight}",`)
    if (start < 0) throw new Error(`${phosphorName} has no ${weight} weight`)
    const end = src.indexOf('\n  ]', start)
    const block = src.slice(start, end)
    const elements = [...block.matchAll(/createElement\("(\w+)", \{([^}]*)\}\)/g)].map(([, tag, attrs]) => {
      const pairs = [...attrs.matchAll(/(\w+): ("[^"]*"|[\d.]+)/g)].map(
        ([, key, value]) => `${kebab(key)}="${value.replace(/^"|"$/g, '')}"`,
      )
      return `<${tag} ${pairs.join(' ')}/>`
    })
    if (elements.length === 0) throw new Error(`${phosphorName} ${weight}: nothing parsed`)
    out[weight] = elements.join('')
  }
  return out
}

const icons = {}
for (const [name, phosphor] of Object.entries(MAP)) icons[name] = weightsOf(phosphor)

const header = `// public/app-prototype/icons.js — GENERATED by scripts/build-app-icons.mjs. Do not edit.
// Phosphor Icons (MIT, https://phosphoricons.com), the website's icon family.
`
fs.writeFileSync('public/app-prototype/icons.js', `${header}window.PLUG_ICONS = ${JSON.stringify(icons)}\n`)
console.log(`wrote ${Object.keys(icons).length} icons x ${WEIGHTS.length} weights`)
