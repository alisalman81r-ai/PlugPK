// scripts/build-app-prototype-data.mjs
//
// Builds public/app-prototype/data.js from the database export, so the app
// prototype shows the same stations, cars, services and posts as the website.
//
//   node scripts/build-app-prototype-data.mjs
//
// Ratings are worked out from the review rows, never the stored rating columns,
// for the same reason the website does it (see src/lib/sample-listings.ts).

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (name) => JSON.parse(readFileSync(join(root, 'data/db-export', `${name}.json`), 'utf8'))
const json = (value, fallback) => {
  try {
    return value ? JSON.parse(value) : fallback
  } catch {
    return fallback
  }
}
// "/images/x.jpg" -> "x.jpg" under the images folder; the app adds its own base.
const img = (path) => (path ? path.replace(/^\/images\//, '') : null)

const reviews = read('review')
const connectors = read('connector')

const stations = read('station').map((s) => {
  const own = reviews.filter((r) => r.stationId === s.id)
  const rating = own.length ? own.reduce((sum, r) => sum + r.rating, 0) / own.length : null
  return {
    id: s.id,
    slug: s.slug,
    name: s.name,
    description: s.description,
    street: s.street,
    area: s.area,
    city: s.city,
    lat: s.lat,
    lng: s.lng,
    amenities: json(s.amenities, []),
    hours: json(s.operatingHours, null),
    photos: json(s.photos, []).map(img),
    network: s.network,
    phone: s.phone,
    venueType: s.venueType,
    rating: rating && Math.round(rating * 10) / 10,
    connectors: connectors
      .filter((c) => c.stationId === s.id)
      .map((c) => ({ type: c.type, kw: c.maxPowerKw, ports: c.ports, cars: json(c.compatibleVehicles, []) })),
    reviews: own.map((r) => ({
      id: r.id,
      name: r.userName,
      car: r.userVehicle,
      rating: r.rating,
      text: r.comment,
      date: r.date,
      helpful: r.helpfulCount,
    })),
  }
})

const num = (v) => (v == null || Number.isNaN(Number(v)) ? null : Number(v))
const cars = read('car').map((c) => ({
  slug: c.slug,
  brand: c.brand,
  model: c.model,
  name: c.fullName,
  category: c.category,
  variant: c.variant,
  year: c.modelYear,
  priceMin: num(c.priceMin),
  priceMax: num(c.priceMax),
  price: c.priceDisplay,
  battery: num(c.batteryCapacity),
  range: num(c.range),
  rangeStd: c.rangeStandard,
  eRange: num(c.electricRange),
  power: num(c.motorPowerKw),
  accel: num(c.acceleration),
  topSpeed: num(c.topSpeed),
  torque: num(c.torque),
  seats: num(c.seats),
  dc: num(c.dcCharging),
  ac: num(c.acCharging),
  connectors: c.connectors,
  body: c.bodyType,
  drive: c.driveType,
  dcMin: num(c.dcChargingMinutes),
  acHours: num(c.acChargingHours),
  length: num(c.lengthMm),
  width: num(c.widthMm),
  height: num(c.heightMm),
  wheelbase: num(c.wheelbaseMm),
  clearance: num(c.groundClearanceMm),
  boot: num(c.bootCapacityL),
  weight: num(c.kerbWeightKg),
  availability: c.availability,
  distributor: c.distributor,
  warranty: c.warranty,
  image: img(c.image),
}))

const services = read('eVService')
  .filter((s) => s.status === 'approved')
  .map((s) => ({
    id: s.id,
    slug: s.slug,
    name: s.name,
    category: s.category,
    description: s.description,
    street: s.street,
    area: s.area,
    city: s.city,
    phone: s.phone,
    email: s.email,
    hours: json(s.operatingHours, null),
    photo: img(s.coverPhoto),
    verified: s.isVerified === true,
  }))

const comments = read('comment')
const posts = read('communityPost').map((p) => ({
  id: p.id,
  slug: p.slug,
  name: p.userName,
  car: p.userVehicle,
  title: p.title,
  body: p.content,
  category: p.category,
  photos: json(p.photos, []).map(img),
  likes: p.likeCount,
  date: p.createdAt,
  comments: comments
    .filter((c) => c.postId === p.id)
    .map((c) => ({ id: c.id, name: c.userName, text: c.content, likes: c.likeCount, date: c.createdAt })),
}))

const clubs = read('club').map((c) => ({
  id: c.id,
  name: c.name,
  city: c.city,
  description: c.description,
  members: c.memberCount,
}))

const data = { stations, cars, services, posts, clubs, builtAt: new Date().toISOString().slice(0, 10) }
const out = join(root, 'public/app-prototype/data.js')
writeFileSync(out, `// Generated by scripts/build-app-prototype-data.mjs. Do not edit by hand.\nwindow.PLUG_DATA = ${JSON.stringify(data)};\n`)
console.log(`Wrote ${out}: ${stations.length} stations, ${cars.length} cars, ${services.length} services, ${posts.length} posts, ${clubs.length} clubs`)
